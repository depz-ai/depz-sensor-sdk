#!/usr/bin/env python3
"""Generate src/main/java/ai/depz/sensor/sensors/vl53l8/Vl53l8Tables.java from the
Python SDK's vl53l8/uld.py: the ST command tables the ULD writes verbatim
(GET_XTALK_CMD, the CALIBRATE_XTALK tables of each firmware) and the
xtalk-calibration output list, so the Java port can never drift from the
reference. The sensor firmware and configuration blobs are not generated: the
build takes the files of vl53l8/data as classpath resources. Stdlib only.

Run from packages/depz-sensor-sdk-java:  python3 scripts/gen_vl53l8_tables.py
     --check: fail when the committed file is stale.
"""
import importlib.util
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
ULD = HERE.parent / "depz-sensor-sdk-python" / "depz_sensor_sdk" / "vl53l8" / "uld.py"
OUT = HERE / "src" / "main" / "java" / "ai" / "depz" / "sensor" / "sensors" / "vl53l8" / "Vl53l8Tables.java"

BYTE_TABLES = [
    ("GET_XTALK_CMD", "getXtalkCmd", "GET_XTALK_CMD", "vl53l8cx_plugin_xtalk.h: the command that reads the xtalk buffer back"),
    ("CALIBRATE_XTALK_CX", "calibrateXtalkCx", "CALIBRATE_XTALK", "VL53L8CX_CALIBRATE_XTALK (ULD 2.1.0)"),
    ("CALIBRATE_XTALK_LMZ", "calibrateXtalkLmz", "CALIBRATE_XTALK_LMZ", "VL53LMZ_CALIBRATE_XTALK (ULD 2.0.16: L8CH, L7CH)"),
    ("CALIBRATE_XTALK_L7CX", "calibrateXtalkL7cx", "CALIBRATE_XTALK_L7CX", "VL53L7CX_CALIBRATE_XTALK (ULD 2.0.1: L5CX, L7CX)"),
]
WORD_TABLES = [
    ("XTALK_CAL_OUTPUT", "xtalkCalOutput", "XTALK_CAL_OUTPUT", "the 17-block output list of the xtalk calibration run"),
    ("XTALK_CAL_OUTPUT_ENABLE", "xtalkCalOutputEnable", "XTALK_CAL_OUTPUT_ENABLE", "the output enables of xtalkCalOutput"),
]


def load_uld():
    # Load uld.py as depz_sensor_sdk.vl53l8.uld so its relative imports resolve,
    # without importing the SDK package itself (its __init__ needs numpy, pyserial).
    sdk = ULD.parent.parent
    for name, path in (("depz_sensor_sdk", sdk), ("depz_sensor_sdk.vl53l8", ULD.parent)):
        if name not in sys.modules:
            pkg = types.ModuleType(name)
            pkg.__path__ = [str(path)]
            sys.modules[name] = pkg
    spec = importlib.util.spec_from_file_location("depz_sensor_sdk.vl53l8.uld", ULD)
    uld = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(uld)
    return uld


def render() -> str:
    uld = load_uld()
    out = [
        "// Vl53l8Tables.java — GENERATED by scripts/gen_vl53l8_tables.py from the Python SDK's",
        "// vl53l8/uld.py; do not edit. ST command tables (VL53L8CX ULD 2.1.0, VL53LMZ ULD 2.0.16,",
        "// VL53L5CX/L7CX ULD 2.0.1), redistributed under ST's BSD-3-Clause licence.",
        "package ai.depz.sensor.sensors.vl53l8;",
        "",
        "/** The ST command tables the VL53L8 / L5 / L7 ULD writes verbatim. Each accessor returns a copy. */",
        "public final class Vl53l8Tables {",
        "    private Vl53l8Tables() {}",
        "",
    ]
    for const, getter, attr, what in BYTE_TABLES:
        data = bytes(getattr(uld, attr))
        out.append(f"    private static final byte[] {const} = hex(")
        h = data.hex()
        chunks = [h[i:i + 96] for i in range(0, len(h), 96)]
        for k, c in enumerate(chunks):
            out.append(f'        "{c}"' + (" +" if k + 1 < len(chunks) else ");"))
        out.append("")
    for const, getter, attr, what in WORD_TABLES:
        words = getattr(uld, attr)
        out.append(f"    private static final int[] {const} = {{")
        for i in range(0, len(words), 6):
            out.append("        " + ", ".join(f"0x{w:08X}" for w in words[i:i + 6]) + ",")
        out.append("    };")
        out.append("")
    for const, getter, attr, what in BYTE_TABLES:
        n = len(getattr(uld, attr))
        out.append(f"    /** {what}; {n} bytes. */")
        out.append(f"    public static byte[] {getter}() {{")
        out.append(f"        return {const}.clone();")
        out.append("    }")
        out.append("")
    for const, getter, attr, what in WORD_TABLES:
        out.append(f"    /** {what} (u32 block headers as Java ints). */")
        out.append(f"    public static int[] {getter}() {{")
        out.append(f"        return {const}.clone();")
        out.append("    }")
        out.append("")
    out += [
        "    private static byte[] hex(String s) {",
        "        byte[] b = new byte[s.length() / 2];",
        "        for (int i = 0; i < b.length; i++) {",
        "            b[i] = (byte) Integer.parseInt(s.substring(2 * i, 2 * i + 2), 16);",
        "        }",
        "        return b;",
        "    }",
        "}",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale: run scripts/gen_vl53l8_tables.py")
            return 1
        print(f"{OUT.name} up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
