package ai.depz.sensor.sensors.vl53lx;

import java.util.Collection;
import java.util.List;

/** VL53L3CX ULP 1.0.0: plain single-target ranging on the histogram part. */
public final class Vl53l3UlpDriver extends Vl53l1Die {
    private static final byte[] DEFAULT_CONFIGURATION = Vl53l4UldDriver.bytes(
        0x00, 0x00, 0x00, 0x11, 0x02, 0x00, 0x02, 0x08, 0x00, 0x08, 0x10, 0x01, 0x01, 0x00, 0x00, 0x00,
        0x00, 0xff, 0x00, 0x0f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20, 0x0b, 0x00, 0x00, 0x02, 0x14, 0x21,
        0x00, 0x00, 0x05, 0x00, 0x00, 0x00, 0x00, 0xc8, 0x00, 0x00, 0x38, 0xff, 0x01, 0x00, 0x08, 0x00,
        0x00, 0x00, 0x01, 0x07, 0x00, 0x02, 0x05, 0x00, 0xb4, 0x00, 0xbb, 0x08, 0x38, 0x00, 0x00, 0x00,
        0x00, 0x0f, 0x89, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x07, 0x05, 0x06, 0x06, 0x00,
        0x00, 0x02, 0xc7, 0xff, 0x9b, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00);

    private static final List<String> GROUPS = List.of("timing", "thresholds", "signal_thresh", "sigma_thresh", "roi");

    public Vl53l3UlpDriver(Vl53lxPlatform platform, String product) {
        super(platform, product);
    }

    @Override
    protected byte[] configuration() {
        return DEFAULT_CONFIGURATION;
    }

    @Override
    protected int stopMode() {
        return 0x00;
    }

    @Override
    public Collection<String> supports() {
        return GROUPS;
    }

    @Override
    protected void initExtra() {
        p.writeWord(0x0024, 0x0500);
        p.writeByte(0x0081, 0x8A); // ULP only
        p.writeByte(PHASECAL_CONFIG_TIMEOUT_MACROP, 0x03);
    }
}
