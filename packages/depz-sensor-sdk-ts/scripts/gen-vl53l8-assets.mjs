#!/usr/bin/env node
/**
 * Generate src/sensors/vl53l8/assets/{cx,ch,l7cx,l7ch}.ts from the Python
 * package's binary blob data (single source of truth for the sensor FW /
 * config blobs). The L5/L7 sets carry only the blobs that differ; the rest
 * are re-exported from the L8 set they share them with (no duplicate base64).
 *
 * Run from packages/depz-sensor-sdk-ts:  bun scripts/gen-vl53l8-assets.mjs
 */

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const dataRoot = path.resolve(
  pkgRoot,
  "..",
  "depz-sensor-sdk-python",
  "depz_sensor_sdk",
  "vl53l8",
  "data",
);
const outDir = path.join(pkgRoot, "src", "sensors", "vl53l8", "assets");
mkdirSync(outDir, { recursive: true });

const FILES = [
  ["firmwareB64", "firmware.bin"],
  ["defaultConfigurationB64", "default_configuration.bin"],
  ["defaultXtalkB64", "default_xtalk.bin"],
  ["getNvmCmdB64", "get_nvm_cmd.bin"],
];

// Where a set's missing blobs live (mirrors uld.py _BLOB_FALLBACK_DIR).
const FALLBACK = { l7cx: "cx", l7ch: "ch" };

for (const variant of ["cx", "ch", "l7cx", "l7ch"]) {
  const dir = path.join(dataRoot, variant);
  let src =
    `// GENERATED by scripts/gen-vl53l8-assets.mjs from\n` +
    `// packages/depz-sensor-sdk-python/depz_sensor_sdk/vl53l8/data/${variant}/ — do not edit.\n` +
    `/* eslint-disable */\n` +
    `import { decodeBase64 } from "./decode.js";\n`;
  const shared = FILES.filter(([, file]) => !existsSync(path.join(dir, file)));
  if (shared.length) {
    const from = FALLBACK[variant];
    if (!from) throw new Error(`${variant}: missing ${shared.map((f) => f[1])} and no fallback set`);
    const names = shared.map(([name]) => name).join(", ");
    src += `import { ${names} } from "./${from}.js";\n`;
    src += `export { ${names} };\n`;
  }
  src += `\n`;
  const sizes = [];
  for (const [name, file] of FILES) {
    const own = existsSync(path.join(dir, file));
    const bytes = readFileSync(path.join(own ? dir : path.join(dataRoot, FALLBACK[variant]), file));
    sizes.push(`${file}: ${bytes.length} bytes`);
    if (!own) continue;
    src += `/** ${file} (${bytes.length} bytes) */\n`;
    src += `export const ${name} =\n  "${bytes.toString("base64")}";\n\n`;
  }
  src +=
    `/** Decode all '${variant}' blobs (${sizes.join(", ")}). */\n` +
    `export function decode(): {\n` +
    `  firmware: Uint8Array;\n` +
    `  defaultCfg: Uint8Array;\n` +
    `  defaultXtalk: Uint8Array;\n` +
    `  getNvmCmd: Uint8Array;\n` +
    `} {\n` +
    `  return {\n` +
    `    firmware: decodeBase64(firmwareB64),\n` +
    `    defaultCfg: decodeBase64(defaultConfigurationB64),\n` +
    `    defaultXtalk: decodeBase64(defaultXtalkB64),\n` +
    `    getNvmCmd: decodeBase64(getNvmCmdB64),\n` +
    `  };\n` +
    `}\n`;
  const outFile = path.join(outDir, `${variant}.ts`);
  writeFileSync(outFile, src);
  console.log(`wrote ${outFile} (${src.length} chars)`);
}
