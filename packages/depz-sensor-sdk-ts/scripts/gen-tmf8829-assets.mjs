#!/usr/bin/env node
/**
 * Generate src/sensors/tmf8829/firmware-asset.ts from the Python package's
 * copy of the ams TMF8829 sensor firmware (single source of truth).
 *
 * Run from packages/depz-sensor-sdk-ts:  bun scripts/gen-tmf8829-assets.mjs
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, "..");
const src = path.resolve(pkgRoot, "..", "depz-sensor-sdk-python", "depz_sensor_sdk", "tmf8829", "data",
  "tmf8829_application.bin");
const bin = readFileSync(src);
const license = readFileSync(path.join(path.dirname(src), "LICENSES-MIT.TXT"), "utf8");
const sha = createHash("sha256").update(bin).digest("hex");
const out = `// GENERATED by scripts/gen-tmf8829-assets.mjs from
// packages/depz-sensor-sdk-python/depz_sensor_sdk/tmf8829/data/tmf8829_application.bin — do not edit.
// ams-OSRAM TMF8829 application 2.200.0, MIT — license text in firmware-license.ts.
/* eslint-disable */

/** tmf8829_application.bin (${bin.length} bytes, sha256 ${sha}) */
export const tmf8829FirmwareB64 =
  "${bin.toString("base64")}";
`;
writeFileSync(path.join(pkgRoot, "src", "sensors", "tmf8829", "firmware-asset.ts"), out);
// Separate module: importing the license must not pull the image into a bundle.
writeFileSync(
  path.join(pkgRoot, "src", "sensors", "tmf8829", "firmware-license.ts"),
  `// GENERATED by scripts/gen-tmf8829-assets.mjs — do not edit.
/* eslint-disable */

/** The MIT license (ams-OSRAM) of the TMF8829 sensor firmware the SDK embeds. */
export const TMF8829_FIRMWARE_LICENSE = ${JSON.stringify(license)};
`,
);
console.log(`firmware-asset.ts: ${bin.length} bytes, sha256 ${sha}`);
