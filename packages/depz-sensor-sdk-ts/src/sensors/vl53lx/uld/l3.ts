/**
 * uld/l3 — VL53L3CX ULP 1.0.0: plain single-target ranging. Async port of the
 * Python `depz_sensor_sdk.vl53lx.uld.l3`. Under the ULP configuration the
 * L3CX and the L4CD are the same machine (same result block, same VCSEL
 * periods), so it sits on `VL53L1Die`; what is its own is the blob, two extra
 * init writes and the stop code.
 */

import {
  CONFIG_ADDR,
  CONFIG_END,
  PHASECAL_CONFIG__TIMEOUT_MACROP,
  VL53L1Die,
} from "./vl53l1-die.js";

export const L3_ULP_VERSION = [1, 0, 0] as const;

/** VL53L3CX_ULP_DEFAULT_CONFIGURATION[] — 91 bytes, registers 0x2D..0x87. */
export const L3_DEFAULT_CONFIGURATION = Uint8Array.from([
  0x00, 0x00, 0x00, 0x11, 0x02, 0x00, 0x02, 0x08, // 0x2D..0x34
  0x00, 0x08, 0x10, 0x01, 0x01, 0x00, 0x00, 0x00, // 0x35..0x3C
  0x00, 0xff, 0x00, 0x0f, 0x00, 0x00, 0x00, 0x00, // 0x3D..0x44
  0x00, 0x20, 0x0b, 0x00, 0x00, 0x02, 0x14, 0x21, // 0x45..0x4C
  0x00, 0x00, 0x05, 0x00, 0x00, 0x00, 0x00, 0xc8, // 0x4D..0x54
  0x00, 0x00, 0x38, 0xff, 0x01, 0x00, 0x08, 0x00, // 0x55..0x5C
  0x00, 0x00, 0x01, 0x07, 0x00, 0x02, 0x05, 0x00, // 0x5D..0x64
  0xb4, 0x00, 0xbb, 0x08, 0x38, 0x00, 0x00, 0x00, // 0x65..0x6C
  0x00, 0x0f, 0x89, 0x00, 0x00, 0x00, 0x00, 0x00, // 0x6D..0x74
  0x00, 0x00, 0x01, 0x07, 0x05, 0x06, 0x06, 0x00, // 0x75..0x7C
  0x00, 0x02, 0xc7, 0xff, 0x9b, 0x00, 0x00, 0x00, // 0x7D..0x84
  0x01, 0x00, 0x00, // 0x85..0x87
]);
if (L3_DEFAULT_CONFIGURATION.length !== CONFIG_END - CONFIG_ADDR + 1) {
  throw new Error("VL53L3CX ULP configuration blob must be 91 bytes");
}

/** Port of VL53L3CX_ULP_api.c (ULP 1.0.0). */
export class VL53L3 extends VL53L1Die {
  /** No offset, crosstalk or calibration: the ULP driver has none. */
  static readonly SUPPORTS: ReadonlySet<string> = new Set([
    "timing",
    "thresholds",
    "signal_thresh",
    "sigma_thresh",
    "roi",
  ]);

  protected readonly CONFIGURATION = L3_DEFAULT_CONFIGURATION;
  /** The ULP writes 0x00 where the VL53L4CD ULD writes 0x80. */
  protected override readonly STOP_MODE: number = 0x00;

  /**
   * The writes closing VL53L3CX_ULP_SensorInit(): the L4CD ULD's
   * ALGO__RANGE_IGNORE_THRESHOLD_MCPS plus two of the ULP's own.
   */
  protected override async initExtra(): Promise<void> {
    await this.p.wrWord(0x0024, 0x0500);
    await this.p.wrByte(0x0081, 0x8a); // 0b10001010, ULP only
    await this.p.wrByte(PHASECAL_CONFIG__TIMEOUT_MACROP, 0x03);
  }
}
