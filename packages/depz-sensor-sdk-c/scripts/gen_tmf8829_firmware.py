#!/usr/bin/env python3
"""Generate src/tmf8829_firmware.c from the Python SDK's TMF8829 sensor
firmware (packages/depz-sensor-sdk-python/depz_sensor_sdk/tmf8829/data), the
single source of truth for the image every SDK embeds, and copy its MIT
licence next to it (licenses/tmf8829/LICENSES-MIT.TXT, installed with the
library).

The image is ams tmf8829_application.hex (application 2.200.0) already turned
into bytes: 14 444 B, load address 0x00010000 (contract 14 §4). Stdlib only.

Run from packages/depz-sensor-sdk-c:  python3 scripts/gen_tmf8829_firmware.py
     --check: fail when the committed files are stale.
"""
import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
DATA = HERE.parent / "depz-sensor-sdk-python" / "depz_sensor_sdk" / "tmf8829" / "data"
IMAGE = DATA / "tmf8829_application.bin"
LICENSE = DATA / "LICENSES-MIT.TXT"
OUT = HERE / "src" / "tmf8829_firmware.c"
OUT_LICENSE = HERE / "licenses" / "tmf8829" / "LICENSES-MIT.TXT"
SHA256 = "973c89b72403a002a76a21647e7ccfaba1a8c3850117faea6f4875b9338a20f8"


def render() -> str:
    data = IMAGE.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256 or len(data) % 4:
        raise SystemExit(f"{IMAGE} is not the contract-14 image (sha256 {SHA256})")
    out = [
        "/* tmf8829_firmware.c — GENERATED by scripts/gen_tmf8829_firmware.py from the",
        " * Python SDK's tmf8829/data; do not edit. ams TMF8829 sensor firmware",
        " * (tmf8829_application.hex, application 2.200.0, load address 0x00010000),",
        " * redistributed under the MIT licence in licenses/tmf8829/LICENSES-MIT.TXT.",
        f" * sha256 {SHA256} */",
        '#include "depz_sensor_sdk.h"',
        "",
        f"const size_t depz_tmf8829_firmware_len = {len(data)};",
        f"const uint8_t depz_tmf8829_firmware[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 20):
        out.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    out.append("};")
    out.append("")
    return "\n".join(out)


def main() -> int:
    text = render()
    lic = LICENSE.read_bytes()
    if "--check" in sys.argv:
        stale = [p.name for p, want in ((OUT, text.encode()), (OUT_LICENSE, lic))
                 if not p.exists() or p.read_bytes() != want]
        if stale:
            print(f"{', '.join(stale)} stale: run scripts/gen_tmf8829_firmware.py")
            return 1
        print(f"{OUT.name}, {OUT_LICENSE.name} up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    OUT_LICENSE.parent.mkdir(parents=True, exist_ok=True)
    OUT_LICENSE.write_bytes(lic)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes) and {OUT_LICENSE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
