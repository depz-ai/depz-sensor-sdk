#!/usr/bin/env python3
"""Generate src/vl53lx/bare/tables.rs from the Python SDK's histogram driver
tables (packages/depz-sensor-sdk-python/depz_sensor_sdk/vl53lx/uld/bare/
regs.py and tuning.py), the single source of truth for them — the Rust twin of
packages/depz-sensor-sdk-c/scripts/gen_vl53lx_bare_tables.py.

regs.py: every register block of ST's BareDriver image with its field list
(offset, width, signedness, the C codec's mask). tuning.py: TUNING (the
tuning-parameter struct after init) and DEFAULTS (the raw header).

Run from packages/depz-sensor-sdk-rust:  python3 scripts/gen_vl53lx_bare_tables.py
     --check: fail when the committed file is stale.
"""
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
BARE = HERE.parent / "depz-sensor-sdk-python" / "depz_sensor_sdk" / "vl53lx" / "uld" / "bare"
OUT = HERE / "src" / "vl53lx" / "bare" / "tables.rs"


def _load(name):
    spec = importlib.util.spec_from_file_location(name, BARE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render():
    regs = _load("regs")
    tuning = _load("tuning")
    o = [
        "//! The register-block layout and the tuning parameters of ST's VL53LX BareDriver — GENERATED by",
        "//! scripts/gen_vl53lx_bare_tables.py from the Python SDK's vl53lx/uld/bare/regs.py and tuning.py",
        "//! (themselves generated from ST's VL53LX BareDriver). Data only: edit the reference, then",
        "//! regenerate (`--check` tells a stale file).",
        "",
        "use super::image::{RegBlockDef, RegField};",
        "",
        "const fn f(",
        "    name: &'static str,",
        "    off: usize,",
        "    width: usize,",
        "    signed: bool,",
        "    mask: Option<i64>,",
        ") -> RegField {",
        "    RegField {",
        "        name,",
        "        off,",
        "        width,",
        "        signed,",
        "        mask,",
        "    }",
        "}",
        "",
        "/// The register blocks of the device image (one `VL53LX_*_t` struct of the C driver each), in",
        "/// address order: base, size, writable and the fields with offset, width, signedness and the mask",
        "/// the C codec applies (`None`: none).",
        "#[rustfmt::skip] // generated table: one field per line",
        "pub static BLOCKS: &[RegBlockDef] = &[",
    ]
    for name, b in regs.BLOCKS.items():
        o.append(f"    RegBlockDef {{")
        o.append(f"        name: \"{name}\",")
        o.append(f"        base: 0x{b.base:04X},")
        o.append(f"        size: {b.size},")
        o.append(f"        writable: {'true' if b.writable else 'false'},")
        o.append(f"        fields: &[")
        for fl in b.fields:
            mask = "None" if fl.mask is None else f"Some(0x{fl.mask:X})"
            o.append(f"            f(\"{fl.name}\", {fl.off}, {fl.width}, {'true' if fl.signed else 'false'}, {mask}),")
        o.append("        ],")
        o.append("    },")
    o.append("];")
    o.append("")
    o.append("/// `VL53LX_tuning_parm_storage_t` after initialisation, keyed by the C field name.")
    o.append("#[rustfmt::skip] // generated table: one parameter per line")
    o.append("pub static TUNING: &[(&str, i64)] = &[")
    for k, v in tuning.TUNING.items():
        o.append(f"    (\"{k}\", {v}),")
    o.append("];")
    o.append("")
    o.append("/// The raw tuning header, for the parameters the post-processing reads without a `tp_` field.")
    o.append("#[rustfmt::skip] // generated table: one parameter per line")
    o.append("pub static DEFAULTS: &[(&str, i64)] = &[")
    for k, v in tuning.DEFAULTS.items():
        o.append(f"    (\"{k}\", {v}),")
    o.append("];")
    o.append("")
    return "\n".join(o)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("stale (run scripts/gen_vl53lx_bare_tables.py): " + OUT.name)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
