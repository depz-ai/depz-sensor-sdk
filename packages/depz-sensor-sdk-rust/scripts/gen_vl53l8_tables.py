#!/usr/bin/env python3
"""Generate src/vl53l8/driver/tables.rs from the Python SDK's vl53l8/uld.py:
the ST command tables the ULD writes verbatim (GET_XTALK_CMD, the
CALIBRATE_XTALK tables of each firmware) and the xtalk-calibration output
list, so the Rust port can never drift from the reference (the Java and C#
SDKs generate theirs the same way). The sensor firmware and configuration
blobs are not generated: scripts/sync_vl53l8_data.py copies them into
src/vl53l8/data, and the driver takes them with include_bytes!. Stdlib only.

Run from packages/depz-sensor-sdk-rust:  python3 scripts/gen_vl53l8_tables.py
     --check: fail when the committed file is stale.
"""
import importlib.util
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
ULD = HERE.parent / "depz-sensor-sdk-python" / "depz_sensor_sdk" / "vl53l8" / "uld.py"
OUT = HERE / "src" / "vl53l8" / "driver" / "tables.rs"

BYTE_TABLES = [
    ("GET_XTALK_CMD", "GET_XTALK_CMD", "vl53l8cx_plugin_xtalk.h: the command that reads the xtalk buffer back"),
    ("CALIBRATE_XTALK_CX", "CALIBRATE_XTALK", "VL53L8CX_CALIBRATE_XTALK (ULD 2.1.0)"),
    ("CALIBRATE_XTALK_LMZ", "CALIBRATE_XTALK_LMZ", "VL53LMZ_CALIBRATE_XTALK (ULD 2.0.16: L8CH, L7CH)"),
    ("CALIBRATE_XTALK_L7CX", "CALIBRATE_XTALK_L7CX", "VL53L7CX_CALIBRATE_XTALK (ULD 2.0.1: L5CX, L7CX)"),
]
WORD_TABLES = [
    ("XTALK_CAL_OUTPUT", "XTALK_CAL_OUTPUT", "the 17-block output list of the xtalk calibration run (u32 block headers)"),
    ("XTALK_CAL_OUTPUT_ENABLE", "XTALK_CAL_OUTPUT_ENABLE", "the output enables of [`xtalk_cal_output`] (one bit per block)"),
]


def load_uld():
    # Load uld.py as depz_sensor_sdk.vl53l8.uld so its relative imports resolve,
    # without importing the SDK package itself (its __init__ needs numpy, pyserial).
    sdk = ULD.parent.parent
    for name, path in (("depz_sensor_sdk", sdk), ("depz_sensor_sdk.vl53l8", ULD.parent)):
        if name not in sys.modules:
            pkg = types.ModuleType(name)
            pkg.__path__ = [str(path)]
            sys.modules[name] = pkg
    spec = importlib.util.spec_from_file_location("depz_sensor_sdk.vl53l8.uld", ULD)
    uld = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(uld)
    return uld


def render() -> str:
    uld = load_uld()
    out = [
        "//! The ST command tables the VL53L8 / L5 / L7 ULD writes verbatim.",
        "//!",
        "//! GENERATED by scripts/gen_vl53l8_tables.py from the Python SDK's vl53l8/uld.py; do not edit.",
        "//! ST command tables (VL53L8CX ULD 2.1.0, VL53LMZ ULD 2.0.16, VL53L5CX/L7CX ULD 2.0.1),",
        "//! redistributed under ST's BSD-3-Clause licence.",
        "",
    ]
    # The arrays stay private and pub fns hand them out (the Java accessors): the API reference
    # (scripts/gen_api_md.py) documents a pub item with its body, and a 1000-byte table is noise.
    for const, attr, what in BYTE_TABLES:
        data = bytes(getattr(uld, attr))
        out.append("#[rustfmt::skip]")
        out.append(f"static {const}: [u8; {len(data)}] = [")
        for i in range(0, len(data), 16):
            out.append("    " + " ".join(f"0x{b:02X}," for b in data[i:i + 16]))
        out.append("];")
        out.append("")
    for const, attr, what in WORD_TABLES:
        words = getattr(uld, attr)
        out.append("#[rustfmt::skip]")
        out.append(f"static {const}: [u32; {len(words)}] = [")
        for i in range(0, len(words), 6):
            out.append("    " + " ".join(f"0x{w & 0xFFFFFFFF:08X}," for w in words[i:i + 6]))
        out.append("];")
        out.append("")
    for const, attr, what in BYTE_TABLES:
        n = len(getattr(uld, attr))
        out.append(f"/// {what}; {n} bytes.")
        out.append(f"pub fn {const.lower()}() -> &'static [u8] {{")
        out.append(f"    &{const}")
        out.append("}")
        out.append("")
    for const, attr, what in WORD_TABLES:
        n = len(getattr(uld, attr))
        out.append(f"/// {what[0].upper()}{what[1:]}; {n} words.")
        out.append(f"pub fn {const.lower()}() -> &'static [u32] {{")
        out.append(f"    &{const}")
        out.append("}")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.name} is stale: run scripts/gen_vl53l8_tables.py")
            return 1
        print(f"{OUT.name} up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
