#!/usr/bin/env python3
"""Generate src/Depz.Sensor/Vl53l8/Vl53l8Tables.g.cs from the Python SDK's
vl53l8/uld.py: the ST command tables the ULD writes verbatim (GET_XTALK_CMD,
the CALIBRATE_XTALK tables of each firmware) and the xtalk-calibration output
list, so the C# port can never drift from the reference. The sensor firmware
and configuration blobs are not generated: Depz.Sensor.csproj embeds the files
of vl53l8/data directly. Stdlib only.

Run from packages/depz-sensor-sdk-csharp:  python3 scripts/gen_vl53l8_tables.py
     --check: fail when the committed file is stale.
"""
import importlib.util
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
ULD = HERE.parent / "depz-sensor-sdk-python" / "depz_sensor_sdk" / "vl53l8" / "uld.py"
OUT = HERE / "src" / "Depz.Sensor" / "Vl53l8" / "Vl53l8Tables.g.cs"

BYTE_TABLES = [
    ("GetXtalkCmd", "GET_XTALK_CMD", "vl53l8cx_plugin_xtalk.h: the command that reads the xtalk buffer back"),
    ("CalibrateXtalkCx", "CALIBRATE_XTALK", "VL53L8CX_CALIBRATE_XTALK (ULD 2.1.0)"),
    ("CalibrateXtalkLmz", "CALIBRATE_XTALK_LMZ", "VL53LMZ_CALIBRATE_XTALK (ULD 2.0.16: L8CH, L7CH)"),
    ("CalibrateXtalkL7cx", "CALIBRATE_XTALK_L7CX", "VL53L7CX_CALIBRATE_XTALK (ULD 2.0.1: L5CX, L7CX)"),
]
WORD_TABLES = [
    ("XtalkCalOutput", "XTALK_CAL_OUTPUT", "the 17-block output list of the xtalk calibration run"),
    ("XtalkCalOutputEnable", "XTALK_CAL_OUTPUT_ENABLE", "the output enables of XtalkCalOutput"),
]


def load_uld():
    # Load uld.py as depz_sensor_sdk.vl53l8.uld so its relative imports resolve,
    # without importing the SDK package itself (its __init__ needs numpy, pyserial).
    sdk = ULD.parent.parent
    for name, path in (("depz_sensor_sdk", sdk), ("depz_sensor_sdk.vl53l8", ULD.parent)):
        if name not in sys.modules:
            pkg = types.ModuleType(name)
            pkg.__path__ = [str(path)]
            sys.modules[name] = pkg
    spec = importlib.util.spec_from_file_location("depz_sensor_sdk.vl53l8.uld", ULD)
    uld = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(uld)
    return uld


def render() -> str:
    uld = load_uld()
    out = [
        "// <auto-generated>",
        "// Vl53l8Tables.g.cs — GENERATED by scripts/gen_vl53l8_tables.py from the Python SDK's",
        "// vl53l8/uld.py; do not edit. ST command tables (VL53L8CX ULD 2.1.0, VL53LMZ ULD 2.0.16,",
        "// VL53L5CX/L7CX ULD 2.0.1), redistributed under ST's BSD-3-Clause licence.",
        "// </auto-generated>",
        "",
        "namespace Depz.Sensor.Vl53l8;",
        "",
        "/// <summary>The ST command tables the VL53L8 / L5 / L7 ULD writes verbatim.</summary>",
        "public static class Vl53l8Tables",
        "{",
    ]
    for name, attr, what in BYTE_TABLES:
        data = getattr(uld, attr)
        out.append(f"    /// <summary>{what}; {len(data)} bytes.</summary>")
        out.append(f"    public static ReadOnlySpan<byte> {name} => new byte[]")
        out.append("    {")
        for i in range(0, len(data), 16):
            out.append("        " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("    };")
        out.append("")
    for name, attr, what in WORD_TABLES:
        words = getattr(uld, attr)
        out.append(f"    /// <summary>{what}.</summary>")
        out.append(f"    public static ReadOnlySpan<uint> {name} => new uint[]")
        out.append("    {")
        for i in range(0, len(words), 6):
            out.append("        " + ", ".join(f"0x{w:08X}" for w in words[i:i + 6]) + ",")
        out.append("    };")
        out.append("")
    out[-1] = "}"
    return "\n".join(out) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale: run scripts/gen_vl53l8_tables.py")
            return 1
        print(f"{OUT.name} up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
